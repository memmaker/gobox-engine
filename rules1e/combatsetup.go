// --- placement (ovr11:19F5) -------------------------------------------

// placement is the DS:4440..4658 state of ovr11:19F5: per side the
// formation templates (4 teams of 6 rows by 11), origin, size and facing.
type placement struct {
	Slots  [2][4][6][11]Slot // DS:4440
	Ox, Oy [2]int8           // DS:4650/4652
	Rows   [2]Count          // DS:4654
	Dir    [2]Dir            // DS:4656
	Side   byte              // DS:4658
}

// cloud is a 0x13-byte DS:6DBB record (linked at +4): a cloud over the
// squares its Kind covers around X, Y (clouds.go).
type cloud struct {
	Kind    CloudKind
	Ptr00   *Character              // +0x00 the caster
	Ground  [cloudSquaresMax]Ground // +0x08 ground under each square
	Covered [cloudSquaresMax]Flag   // +0x0C square is covered
	X, Y    byte                    // +0x10
	Num     byte                    // +0x12 the caster's cloud number (affect data >> 4; a delayed blast's affect data)
	Level   int                     // extra: a delayed blast's caster level, the burst's dice (Felix: at the level cast)
}
