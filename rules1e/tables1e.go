// Package rules1e is the 1st edition ruleset: its tables and rules, the Forgotten
// Realms concepts (dnd.go) and the byte-record character files and layouts
// (char*.go). It imports only gobox/rules.
package rules1e

import "gobox/rules"

// Tables are a 1st edition game's rule tables; POR is the first instance.
// Rows run on past their levels into neighbouring data as in the original.
// Fixes land as separate commits, listed in gobox-engine/CHANGES-FROM-ORIGINAL.md.
type Tables struct {
	ItemMends       []ItemMend // the game's data fixes (MendItem); POR's PorItemMends, a rules.json game its itemMends
	HitDieCount     []int16
	HitDieSides     []int16
	Thac0           [][]int16
	ThiefByLevel    [][]int16
	ThiefByRace     [][]int8
	ThiefByDex      [][]int8
	ConHPByScore    []int8
	XP              [][]int32 // by class, by level: the experience the level takes; ends at the table's end (xpRows)
	XPPast          [][]int32 // by class, by level: the experience past XP's end (POD's expTable, Felix: all games)
	XPSteps         []int32   // by class: what each level past XPPast adds, up to xpTop (POD's steps, Felix 20:05: all games)
	ClericSpells    [][]int16 // by class level, the spells of each spell level (POR 3, COTAB 5, SotSB 7, POD 9)
	MageSpells      [][]int16
	SlotLevels      int       // the last class level the slot rows hold (POR 6: its rows run on into other data)
	SlotsClamp      bool      // past SlotLevels the last row holds (the imported tables, as POD's slotsAt); false: the record keeps its slots (POR)
	Saves           [][]int16 // by class row * SaveRows + level, 5 saves each
	SaveRows        int       // the levels each class has in Saves
	PaladinSaves    [][]int16
	MonkOldSaves    [][]int16 // a monk's saves at its old level, by level (COTAB oldClassSaveData)
	PaladinSpells   [][]int16 // cleric spells levels 1..5 a paladin level adds, by level (COTAB paladinSlotData)
	RangerSpells    [][]int16 // druid 1..3 and magic-user 1..2 spells a ranger level adds, by level (COTAB rangerSlotData)
	RaceClasses     [][]int16
	StartAge        [][]ageDice
	AgeSteps        [][]int32
	ClassMinStats   [][]int16
	ClassAlignments [][]int16
	RaceLimits      []raceLimit
	TurnUndead      [][]int8
	Spells          [][]SpellProp              // spell records, by unified spell id (SpellMap)
	Races           []rules.Race               // the race of each of the game's race numbers (Layout.Races); nil: POR, its numbers are RaceIDs
	CasterLevel     CasterLevelRule            // the game's caster-level rule (rules.json casterLevel); zero: POR's
	OldAge          *OldAgeRule                // death of old age after a fight (rules.json oldAge); nil: none (POR, CotAB)
	Hammer          *Item                      // the Spiritual Hammer (rules.json spiritualHammer); nil: POR's
	Resist          *MagicResistRule           // the game's own magic resistance (rules.json magicResistance); nil: none
	Giants          GiantRule                  // how the game tells a giant (rules.json giantRule); zero: POR's
	AffectRule      AffectRule                 // the game's affect laying and ending (rules.json affectRule); zero: POR's
	ItemSpell       *ItemSpellCode             // how an item's +0x3D holds its spell (rules.json itemSpellCode); nil: POR's (PorItemSpell)
	SpellIDs        SpellMap                   // the game's spell numbers as ids (rules.json spellIds); nil: POR, its numbers are the ids
	SpellsGone      SpellMap                   // removed spells' numbers as the id a record holding one reads (one way; 0: none) (rules.json spellsGone)
	Ground          [][]GroundProp             // ground properties, by ground number (rules.json groundInfo)
	Terrain         []TerrainFlag              // the terrain flags of each terrain number (rules.json wildTerrainFlags); POR's: TerrainKinds
	Gen             GroundGen                  // how the combat ground is laid (rules.json combatGround); POR's: PorGroundGen
	Kinds           ItemKinds                  // the dnd id of each base item type (rules.json itemKinds); nil: POR's ItemIDs
	MoraleUncapped  bool                       // a morale roll above 102 stands as it is (rules.json moraleUncapped; PoD CheckMorale); false: read as 0 (POR, CotAB, SotSB)
	Grounds         GroundIDs                  // the grounds the rules lay (rules.json groundIds); POR's: PorGroundIDs
	ClassMask       []ClassBits                // class bits, by class
	HpClassMask     []ClassBits                // the classes whose hit dice a level rolls, by class
	Affects         map[AffectType]HandlerName // the handler of each affect number
	Groups          [][]AffectType             // the affect groups by meaning (grp*; rules.json affectGroups); nil: POR's affectGroups
	AffectIDs       AffectMap                  // the game's affect numbers as ids (rules.json affectIds); nil: POR, its numbers are the ids
	PowerIDs        PowerMap                   // the game's item power codes as unified powers (rules.json itemPowers); nil: POR, its codes are the powers
	ImportFlag      bool                       // a character added from another game is flagged as imported (rules.json importFlag; COTAB: as from Hillsfar)
	Start           StartData                  // a new character's per-adventure start (rules.json creationStart)
	Town            TownData                   // the town economy: the hall fee and the temple (rules.json town); POR: porTown
	Library         []*Item                    // the data set's item library, by id-1; nil: an empty entry (rules.json itemLibrary, POD ITEM0)
	Scroll          *RandomScroll              // how a random scroll is made (rules.json randomScroll, POD O055:1ABE); nil: the game has none
	Treasure        *TreasureRolls             // random treasure (rules.json randomTreasure); nil: POR's RandomItemType and RandomItem
	Appraisal       *Appraisal                 // how a gem or jewel is valued (rules.json appraisal); nil: PorAppraisal
}

// RandomScroll is a random scroll's making: the item, then each of its
// spells rolled 1..Last until it is one of Mage.
type RandomScroll struct {
	Type   ItemType
	Words  [3]WordID
	Plus   byte
	Weight uint16
	Price  uint16
	Last   int
	Mage   []SpellID
}

