package engine

import (
	"flag"
	"fmt"
	"gobox/ecl"
	"gobox/rules"
	"os"
	"slices"
	"strings"
	"testing"
)

var updatePics = flag.Bool("update", false, "rewrite beastpics.go from the scripts")

// TestBeastPics reads, from every ECL script, the picture shown before each
// fight's monsters are loaded: opSetupMonster's close-up (its third
// operand) or opPicture's, the nearest before the opLoadMonster in the
// block. The kind's most common one is its bestiary picture (beastPics);
// -update rewrites beastpics.go.
func TestBeastPics(t *testing.T) {
	e := testEngine(t)
	e.Init() // the item table: a monster's items map through it (rules1e Rules.monster)
	count := map[string]map[int]int{}
	for disk := 1; disk <= 8; disk++ { // each set's ECL and MON files hold its own blocks (ovr18:0EC4 reads the set's alone)
		e.set = rules.Set(disk)
		for block := 1; block < 0x40; block++ {
			b := refDAX(e).BlockShared(fmt.Sprintf("ECL%d", disk), block)
			if len(b) < 2 {
				continue
			}
			_, lines, _ := ecl.V1.Walk(b[2:])
			pic := -1
			for _, pc := range ecl.SortedPCs(lines) {
				l := lines[pc]
				lit := func(i int) int {
					if i >= len(l.Args) || l.Args[i].Type != ecl.ArgByte {
						return -1
					}
					return l.Args[i].N
				}
				switch l.Cmd.Op {
				case 0x0C:
					pic = lit(2)
				case ecl.OpPicture:
					pic = lit(0)
				case 0x0B:
					idx := lit(0)
					if pic < 0 || pic == 0xFF || idx < 0 {
						continue
					}
					if refDAX(e).BlockShared(e.set.File("MON")+"CHA", idx) == nil {
						continue
					}
					id, ok := e.LoadMonster(idx)
					if !ok {
						continue
					}
					c := e.member(id)
					if bt := beastOf(c.Name()); bt != nil {
						if count[bt.Name] == nil {
							count[bt.Name] = map[int]int{}
						}
						count[bt.Name][pic]++
					}
				}
			}
		}
	}
	got := map[string]int{}
	for name, m := range count {
		best := -1
		for k, n := range m {
			if best < 0 || n > m[best] || n == m[best] && k < best {
				best = k
			}
		}
		got[name] = best
	}
	if *updatePics {
		var s strings.Builder
		s.WriteString("// Code generated by TestBeastPics -update; DO NOT EDIT.\n\npackage rules\n\n// beastPics is each kind's picture in the picture window when the scripts\n// set its fight up (the PIC block: DOS and Amiga number them alike).\nvar beastPics = map[string]int{\n")
		names := make([]string, 0, len(got))
		for n := range got {
			names = append(names, n)
		}
		slices.Sort(names)
		for _, n := range names {
			fmt.Fprintf(&s, "\t%q: %d,\n", n, got[n])
		}
		s.WriteString("}\n")
		if err := os.WriteFile("beastpics.go", []byte(s.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	for n, p := range got {
		if beastPics[n] != p {
			t.Errorf("%s: scripts give %v, beastPics %v (go test -run TestBeastPics -update)", n, p, beastPics[n])
		}
	}
	if len(got) != len(beastPics) {
		t.Errorf("%d kinds from the scripts, %d in beastPics", len(got), len(beastPics))
	}
}
